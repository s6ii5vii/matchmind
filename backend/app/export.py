"""Write the simulated match to data/ as CSV and JSON so people can open it.

Run from backend/:  python -m app.export
"""

import csv
import json
from pathlib import Path

from .synthetic import EVENTS, GOALS, SQUADS, TEAMS

DATA_DIR = Path(__file__).resolve().parents[2] / "data"
COLUMNS = ["id", "clock", "minute", "second", "t", "team", "player", "number", "position", "type", "outcome",
           "x", "y", "end_x", "end_y", "zone", "receiver", "under_pressure", "distance_m", "difficulty", "xg",
           "body_part", "is_goal", "possession", "possession_team", "possession_end"]


def match_json() -> dict:
    return {
        "note": "Fictional match generated by backend/app/synthetic.py. Not real Premier League data.",
        "teams": TEAMS,
        "squads": {side: [{"number": n, "position": p, "name": name} for n, p, name in squad]
                   for side, squad in SQUADS.items()},
        "goals": [{"minute": m, "second": s, "team": t, "scorer": p, "xg": x} for m, s, t, p, x in GOALS],
        "events": [{k: e.get(k) for k in COLUMNS} for e in EVENTS],
    }


def write() -> None:
    DATA_DIR.mkdir(exist_ok=True)
    (DATA_DIR / "match.json").write_text(json.dumps(match_json(), indent=1) + "\n")
    with open(DATA_DIR / "match_events.csv", "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=COLUMNS)
        writer.writeheader()
        writer.writerows({k: e.get(k) for k in COLUMNS} for e in EVENTS)
    print(f"Wrote {len(EVENTS)} events to {DATA_DIR}")


if __name__ == "__main__":
    write()
