"""Write every simulated match to data/ as CSV and JSON so people can open them.

Run from backend/:  python -m app.export
"""

import csv
import json
from pathlib import Path

from .synthetic import EVENTS, GOALS, MATCHES, SQUADS, TEAMS, current_match, match_meta, use_match

DATA_DIR = Path(__file__).resolve().parents[2] / "data"
COLUMNS = ["id", "period", "clock", "label", "minute", "second", "t", "team", "player", "number", "position",
           "type", "outcome", "x", "y", "end_x", "end_y", "zone", "receiver", "pass_type", "under_pressure",
           "distance_m", "difficulty", "xg", "body_part", "is_goal", "duration_s", "possession", "possession_team",
           "possession_end"]


def match_json() -> dict:
    """The current match (see synthetic.use_match)."""
    spec, meta = current_match(), match_meta()
    return {
        "note": "Fictional match generated by backend/app/synthetic.py. Not real Premier League data.",
        "id": spec.id,
        "story": spec.story,
        "teams": dict(TEAMS),
        "squads": {side: [{"number": n, "position": p, "name": name} for n, p, name in squad]
                   for side, squad in SQUADS.items()},
        "bench": {side: [{"number": n, "position": p, "name": name} for n, p, name in squad]
                  for side, squad in spec.bench.items()},
        "added_time": {"first_half": meta["added"][1], "second_half": meta["added"][2]},
        "minutes_played": meta["length"],
        "goals": [{"minute": m, "second": s, "team": t, "scorer": p, "xg": x} for m, s, t, p, x in GOALS],
        "events": [{k: e.get(k) for k in COLUMNS} for e in EVENTS],
    }


def write() -> None:
    DATA_DIR.mkdir(exist_ok=True)
    for match_id in MATCHES:
        with use_match(match_id):
            (DATA_DIR / f"{match_id}.json").write_text(json.dumps(match_json(), indent=1, ensure_ascii=False) + "\n")
            with open(DATA_DIR / f"{match_id}.csv", "w", newline="", encoding="utf-8") as f:
                writer = csv.DictWriter(f, fieldnames=COLUMNS)
                writer.writeheader()
                writer.writerows({k: e.get(k) for k in COLUMNS} for e in EVENTS)
            print(f"Wrote {len(EVENTS)} events of {match_id} to {DATA_DIR}")


if __name__ == "__main__":
    write()
